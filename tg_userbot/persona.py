def silence_step(*, last_role: str, last_ts: float, reminded_at: float | None,
                 closed_at: float | None, now: float,
                 remind_after: float = REMIND_AFTER_S,
                 close_after: float = CLOSE_AFTER_S) -> str | None:
    """"remind", "close" or None for a chat, from who spoke last and when."""
    if last_role != "assistant" or closed_at:
        return None
    if reminded_at is None:
        return "remind" if now - last_ts >= remind_after else None
    return "close" if now - reminded_at >= close_after else None


def nudge_hours(now_kyiv) -> bool:
    """Reminders go out Monday to Saturday, 10:00-19:00 Kyiv time."""
    return now_kyiv.weekday() < 6 and 10 <= now_kyiv.hour < 19


# Our timestamps and Telegram's come from different clocks.
_CLOCK_SLACK_S = 5.0


def is_unseen(*, sent_at: float, text: str, known: set[str], last_seen: float) -> bool:
    """Did this incoming message arrive while Eva was not listening?

    Text alone is not enough: a candidate who edits an old message makes Telegram
    return the new wording under the OLD date, and matching by text took it for a
    fresh one (28.09: a message from 18.09 came back as new and re-alerted the
    recruiters). Anything older than our newest stored message was already seen.
    """
    if not text or text in known:
        return False
    return sent_at > last_seen - _CLOCK_SLACK_S


# Checked in this order: Telegram also marks a voice note or a sticker as a document.
_ATTACHMENTS = (
    ("voice", "[голосове повідомлення]"),
    ("video_note", "[відеоповідомлення]"),
    ("sticker", "[стікер]"),
    ("photo", "[фото]"),
    ("document", "[файл]"),
)


def incoming_text(message) -> str:
    """What Eva reads from an incoming message: its text, else a placeholder for the
    attachment, else "" (nothing to answer). Never store an empty turn — the API
    refuses the whole conversation after one."""
    text = (getattr(message, "raw_text", None) or "").strip()
    if text:
        return text
    for attr, placeholder in _ATTACHMENTS:
        if getattr(message, attr, None):
            return placeholder
    return ""

